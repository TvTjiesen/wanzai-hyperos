# -*- coding: utf-8 -*-
"""Generate the app's parallel-eye policy, never legacy rendered DOM.

MIT Grok Ball (https://github.com/tycoding/grok-ball) remains the source of
animation/body APIs. Eye geometry is the app's explicit safe-face policy.
Default invocation writes two Kotlin artifacts and the marked debug JS block.
--check is read-only and exits nonzero on drift. No browser or network is used.
"""
import argparse
import json
from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
AI = BASE / 'app/src/main/java/com/muyao/wanzaihyperos/ui/design/ai'
DEBUG = BASE / 'app/src/debug/assets/grokball'
START = '// BEGIN GENERATED SAFE FACE POLICY'
END = '// END GENERATED SAFE FACE POLICY'


def load_policy():
    p = json.loads((DEBUG / 'safe-face-policy.json').read_text(encoding='utf-8'))
    assert p['version'] == 1 and p['points'] == 48
    assert len(p['states']) == 12 and len({s['state'] for s in p['states']}) == 12
    assert len({(s['width'], s['height'], s['y']) for s in p['states']}) == 12
    for s in p['states']:
        assert 0 < s['width'] < 2 * p['eyeCenterX']
        assert 0 < s['height'] < .2 and abs(s['y']) < .1
    return p


def policy_kotlin(p):
    rows = '\n'.join('        AiBallState.%s -> Face(%.3ff, %.3ff, %.3ff)' %
                     (s['state'], s['width'], s['height'], s['y']) for s in p['states'])
    return '''package com.muyao.wanzaihyperos.ui.design.ai

import kotlin.math.PI
import kotlin.math.cos
import kotlin.math.sin

/** Generated safe-face policy v1. MIT Grok Ball motion attribution retained; no legacy eye rings. */
internal object AiBallFacePolicy {
    const val POINTS = 48
    const val EYE_CENTER_X = 0.145f
    data class Face(val width: Float, val height: Float, val y: Float)

    fun faceOf(state: AiBallState): Face = when (state) {
%s
    }

    /** Equal, horizontal stadiums translated to fixed separated centers; no inward tilt. */
    fun eyesOf(state: AiBallState): List<FloatArray> {
        val face = faceOf(state)
        val radius = minOf(face.width, face.height) / 2.0
        val horizontal = face.width / 2.0 - radius
        val vertical = face.height / 2.0 - radius
        return listOf(-EYE_CENTER_X, EYE_CENTER_X).map { center ->
            FloatArray(POINTS * 2).also { out ->
                repeat(POINTS) { i ->
                    val angle = 2.0 * PI * i / POINTS
                    val cx = cos(angle)
                    val sy = sin(angle)
                    out[i * 2] = (center + radius * cx + if (cx >= 0) horizontal else -horizontal).toFloat()
                    out[i * 2 + 1] = (face.y + radius * sy + if (sy >= 0) vertical else -vertical).toFloat()
                }
            }
        }
    }
}
''' % rows


def glyph_kotlin(p):
    rows = '\n'.join('    val %s = AiBallFacePolicy.eyesOf(AiBallState.%s)' %
                     (s['state'].upper(), s['state']) for s in p['states'])
    mapping = '\n'.join('        AiBallState.%s -> %s' %
                        (s['state'], s['state'].upper()) for s in p['states'])
    return '''package com.muyao.wanzaihyperos.ui.design.ai

/** Generated by tools/gen_ai_ball_glyphs.py from safe-face-policy.json; --check verifies drift.
 * Body/animation attribution: MIT Grok Ball, https://github.com/tycoding/grok-ball.
 * Normalized diameter = 1, center = (0, 0). No rendered legacy DOM is imported.
 */
internal object AiBallGlyphs {
    const val EYE_COLOR = 0xFF111516
    val BODY_STOPS = floatArrayOf(0.00f, 0.62f, 1.00f)
    val BODY_COLORS = intArrayOf(0xFFF6F3EE.toInt(), 0xFFF3F0E9.toInt(), 0xFFD6D3CD.toInt())
    const val GRADIENT_CX = 0.38f
    const val GRADIENT_CY = 0.32f
    const val GRADIENT_R = 0.75f

%s

    fun eyesOf(state: AiBallState): List<FloatArray> = when (state) {
%s
    }
}
''' % (rows, mapping)


def js_block(p):
    rows = ',\n'.join('  [%s, %s, %s]' % (s['width'], s['height'], s['y']) for s in p['states'])
    ids = json.dumps({s['id']: i for i, s in enumerate(p['states'])}, separators=(',', ':'))
    return START + '''
// MIT Grok Ball animation APIs retained; application-owned parallel-eye geometry.
window.EB_SAFE_FACE = (function () {
  var specs = [
%s
  ];
  var ids = %s;
  function ring(center, spec) {
    var radius = Math.min(spec[0], spec[1]) / 2;
    var horizontal = spec[0] / 2 - radius, vertical = spec[1] / 2 - radius;
    var result = [];
    for (var i = 0; i < 48; i++) {
      var angle = 2 * Math.PI * i / 48, cx = Math.cos(angle), sy = Math.sin(angle);
      result.push([114.2705 + 228.54 * (center + radius * cx + (cx >= 0 ? horizontal : -horizontal)),
                   114.2705 + 228.54 * (spec[2] + radius * sy + (sy >= 0 ? vertical : -vertical))]);
    }
    return result;
  }
  var pairs = specs.map(function (s) { return [ring(-0.145, s), ring(0.145, s)]; });
  function pairOf(index) { return pairs[index %% pairs.length]; }
  return {
    indexOf: function (id) { return Object.prototype.hasOwnProperty.call(ids, id) ? ids[id] : 2; },
    pairOf: pairOf,
    expressions: Array.from({length: 25}, function (_, i) { return pairOf(i); }),
    // This final pose gate covers seed/default, register/import, AI messages, tours and sequences.
    constrain: function (pose) {
      var a = pose.left, b = pose.right;
      ['x', 'y', 'lookX', 'lookY', 'scaleX', 'scaleY', 'open'].forEach(function (key) {
        var fallback = key === 'scaleX' || key === 'scaleY' || key === 'open' ? 1 : 0;
        var av = Number.isFinite(a[key]) ? a[key] : fallback;
        var bv = Number.isFinite(b[key]) ? b[key] : fallback;
        var shared = (av + bv) / 2;
        if (key === 'x' || key === 'y') shared = 0;
        if (key === 'lookX' || key === 'lookY') shared = Math.max(-24, Math.min(24, shared));
        if (key === 'scaleX' || key === 'scaleY') shared = 1;
        if (key === 'open') shared = Math.max(0.02, Math.min(1.3, shared));
        a[key] = b[key] = shared;
      });
      a.rotate = b.rotate = 0;
      // Rebuild even externally supplied rings: bounds may vary, old oblique paths cannot survive.
      if (a.ring || b.ring) {
        var source = a.ring || b.ring;
        var xs = source.map(function (p) { return p[0]; }), ys = source.map(function (p) { return p[1]; });
        var minX = Math.min.apply(null, xs), maxX = Math.max.apply(null, xs);
        var minY = Math.min.apply(null, ys), maxY = Math.max.apply(null, ys);
        var width = Math.max(0.05, Math.min(0.16, (maxX - minX) / 228.54));
        var height = Math.max(0.014, Math.min(0.18, (maxY - minY) / 228.54));
        var y = Math.max(-0.05, Math.min(0.05, ((minY + maxY) / 2 - 114.2705) / 228.54));
        var spec = [Number.isFinite(width) ? width : 0.09, Number.isFinite(height) ? height : 0.125,
                    Number.isFinite(y) ? y : 0];
        a.ring = ring(-0.145, spec); b.ring = ring(0.145, spec);
      }
      pose.body.scale = 1;
      pose.body.breathe = 0;
      return pose;
    }
  };
})();
''' % (rows, ids) + END


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    p = load_policy()
    js = DEBUG / 'grok-ball.js'
    text = js.read_text(encoding='utf-8')
    if START in text:
        before, tail = text.split(START, 1)
        _, after = tail.split(END, 1)
        text = before + js_block(p) + after
    else:
        raise SystemExit('Missing safe policy markers; do not regenerate legacy rings')
    outputs = {AI / 'AiBallFacePolicy.kt': policy_kotlin(p), AI / 'AiBallGlyphs.kt': glyph_kotlin(p), js: text}
    drift = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode('utf-8'): drift.append(str(path.relative_to(BASE)))
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    if drift: raise SystemExit('Safe face generation drift: ' + ', '.join(drift))
    print('Safe face policy v1: 12 distinct states, parallel eyes; ' + ('CHECK OK' if args.check else 'GENERATED'))


if __name__ == '__main__':
    main()
