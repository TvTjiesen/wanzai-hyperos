package com.muyao.wanzaihyperos.data.schedule

/**
 * 浙大城市学院的**节次→几点**表（学校日历给的，不是我们编的）。
 *
 * ## 来源（业主 2026-10-20 给的文件：`日历-浙大城市学院.ics`）
 *
 * 教务系统那张表**根本不给几点**（它给的全部具名栏位是 `节/周`、`上课地点`、`教师`、
 * `教学班名称`、`教学班组成`、`考核方式`、`选课备注`、`课程学时组成`、`周学时`、
 * `总学时`、`学分` —— 见 `docs/B22-JW-CELL-HTML.txt`；左列只有「上午/下午/晚上」+ 节次号 1..12），
 * 学在城院 `teaching-weeks` 也只有周次与日期。所以这一份是从他给的日历文件里**推出来**的：
 *
 * - 文件里 53 个 `VEVENT`，每个都带 `第a - b节` + 真实的 `DTSTART`/`DTEND`；
 * - 11 种 `(a,b)→(起,止)` 组合，**每一种只有一种时刻写法，互不自相矛盾**；
 * - 用反推表回代每个事件：11/11 与原文件一致（这条自检已经做成单测）。
 *
 * ## ★ 导出器把下午写成了 12 小时制
 *
 * 原文件里 `DTEND:20260924T021500`（第5-6节，11:30 起）—— 那是 **14:15**，
 * WakeUp 导出时把下午的时间按 12 小时制写了（`013000`=13:30、`021500`=14:15）。
 * 修正判据：`0~3 点不可能有课 ⇒ +12 小时`。这条修正不是猜的，
 * 修完之后「每节 45 分钟、相邻两节间隔 5 分钟」在**五处独立观测**上同时成立
 * （第6节 13:30-14:15、第7节 14:20-15:05、第8节 15:20-16:05、第9节 16:10-16:55、第10节 18:30-19:15）。
 *
 * ## 为什么有几节是空的（而不是凑满 12 行）
 *
 * 只填**文件里直接观测到的那一头**。第 1 节几点下课、第 2 节几点上课，
 * 文件里从来没有单独出现过（只出现过「第1-2节 08:00-09:35」这一对），
 * 所以留空 —— 由 [PeriodClock] 用「起于第1节的课 + 止于第2节的课」拼出区间，
 * 而不是把 45 分钟规律外推成"第1节下课 08:45"这种**我们算出来的值**。
 * 他自己在設定里填过的那一格**优先于这张表**（见 [PeriodClock]）。
 *
 * ## 顺带挖出来的一件事：同一门课在国庆前后换了时段
 *
 * 文件里 B/S 架构应用开发（理4-226 赵磊，周一）有两条：
 * 第 1~3 周 `第5-8节 11:30-16:05`，第 5 周起 `第6-9节 13:30-16:55`；
 * 数据结构与算法（理4-205）、面向对象程序设计（理4-220）、城市和电影（教五110）同样各两条。
 * 而教务那份**只写 `第6-9节`（全部周次）** —— 也就是说看第 1~3 周时，
 * 按教务的节次号去查这张表会得到 13:30，而那年那几周真的是 11:30 上课。
 * 现在（第 6 周）用的是换过之后的那一套，所以下面按 `第6-9节` 登记。
 */
object SchoolPeriods {

    /**
     * 第 N 节 → (上课, 下课)；`null` 那一头 = **日历文件里没有单独观测到**。
     * 索引 0 = 第 1 节。
     */
    val table: List<Pair<String?, String?>> = listOf(
        "08:00" to null,   // 第 1 节：只作为「第1-2节」的起点出现过
        null to "09:35",   // 第 2 节：只作为「第1-2节」的止点出现过
        "09:50" to null,
        null to "11:25",
        "11:30" to null,   // 第 5 节：只在「第5-6节/第5-8节」里作为起点出现过
        "13:30" to "14:15",
        "14:20" to "15:05",
        "15:20" to "16:05",
        "16:10" to "16:55",
        "18:30" to "19:15",
        null to "20:05",   // 第 11 节：只作为「第10-11节」的止点出现过
    )

    /** 第 [period] 节几点上课（越界或没观测到 = null）。 */
    fun startOf(period: Int): String? = table.getOrNull(period - 1)?.first

    /** 第 [period] 节几点下课。 */
    fun endOf(period: Int): String? = table.getOrNull(period - 1)?.second

    /** 这张表覆盖了几节（設定页那句「学校日历给了 N 节」用）。 */
    val coveredCount: Int get() = table.count { it.first != null || it.second != null }

    /**
     * 日历文件里**逐字出现过**的区间 → 时刻。
     *
     * 单测拿它和 [table] 的两端互相对账：任何一头被改错，这里就会不一致
     * （比只测"label 返回某个字符串"更结实，因为它测的是**这份表自不自洽**）。
     */
    val observedRanges: List<Triple<Int, Int, String>> = listOf(
        Triple(1, 2, "08:00-09:35"),
        Triple(3, 4, "09:50-11:25"),
        Triple(1, 4, "08:00-11:25"),
        Triple(5, 6, "11:30-14:15"),
        Triple(5, 8, "11:30-16:05"),
        Triple(6, 7, "13:30-15:05"),
        Triple(6, 9, "13:30-16:55"),
        Triple(7, 8, "14:20-16:05"),
        Triple(8, 9, "15:20-16:55"),
        Triple(9, 10, "16:10-19:15"),
        Triple(10, 11, "18:30-20:05"),
    )
}
